import {randomBytes} from 'node:crypto';
import sanitizeHtml from 'sanitize-html';
import {escapeShareHtml, normalisePublicNewsletterUrl, readerShareBar, READER_SHARE_RUNTIME} from './reader-social-share';
import type {PublishedNewsletter} from './newsletter-publication-store';

const allowedTags = [
  'div','span','p','h1','h2','h3','h4','h5','h6','br','hr','strong','b','em','i',
  'a','img','button','section','article','header','footer','nav','figure','figcaption',
  'ul','ol','li','blockquote','table','tbody','thead','tr','td','th','iframe','small','sup','sub','details','summary',
];

const maxBodyLength=5_500_000;

export function sanitiseNewsletterBody(exportedHtml:string):string {
  // Use the HTML generated by BÜLTEN READ. Never publish its embedded scripts
  // or trust client-side share URLs. The reader gets a freshly generated share bar.
  if(!exportedHtml.includes('bulten-reading-content'))throw new Error('Bülten içeriği bulunamadı.');
  const match=exportedHtml.match(/<body\b[^>]*>([\s\S]*?)<\/body>/i);
  if(!match)throw new Error('Bülten HTML yapısı geçersiz.');
  const withoutShare=match[1]
    .replace(/<section\b[^>]*\bid=["']bulten-reader-share["'][^>]*>[\s\S]*?<\/section>/gi,'')
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'');
  if(withoutShare.length>maxBodyLength)throw new Error('Bülten boyutu sınırı aşıldı.');
  const clean=sanitizeHtml(withoutShare,{
    allowedTags,
    allowedAttributes:{
      '*':['style','id','class','role','title','lang','aria-label','aria-live','aria-hidden'],
      a:['href','target','rel','style','title','aria-label'],
      img:['src','alt','width','height','loading','style','class','title'],
      iframe:['src','title','width','height','style','loading','allowfullscreen'],
      button:['type','id','style','aria-label'],
    },
    allowedSchemes:['http','https','mailto'],
    allowedSchemesByTag:{img:['http','https','data'],a:['http','https','mailto'],iframe:['https']},
    allowedIframeHostnames:['www.youtube.com','youtube.com','www.youtube-nocookie.com'],
    allowProtocolRelative:false,
    disallowedTagsMode:'discard',
    transformTags:{
      a:(tagName,attribs)=>({
        tagName:'a',
        attribs:{...attribs,rel:'noopener noreferrer',target:attribs.href&&attribs.href!=='#'?'_blank':'_self'},
      }),
      img:(tagName,attribs)=>{
        const imageUrl=attribs.src||'';
        if(imageUrl.startsWith('data:')&&!/^data:image\/(?:png|jpeg|webp|gif);base64,[A-Za-z0-9+/=]+$/i.test(imageUrl)){
          delete attribs.src;
        }
        return {tagName:'img',attribs};
      },
    },
  });
  if(!clean.includes('bulten-reading-content'))throw new Error('Okunabilir bülten içeriği bulunamadı.');
  return clean;
}

const READER_SPEECH_SCRIPT = `
(function(){
  'use strict';
  var button=document.getElementById('speakBtn');
  if(!button)return;
  var active=false;
  function update(isPlaying){
    active=isPlaying;
    var label=document.getElementById('speakText');
    var icon=document.getElementById('speakIcon');
    if(label)label.textContent=isPlaying?'Durdur':'Dinle';
    if(icon)icon.textContent=isPlaying?'⏸':'🔊';
  }
  button.addEventListener('click',function(){
    if(!('speechSynthesis' in window))return;
    if(active){window.speechSynthesis.cancel();update(false);return;}
    var heading=document.querySelector('h1');
    var content=document.getElementById('bulten-reading-content');
    var text=(heading?heading.textContent+'. ':'')+(content?content.textContent:'');
    var utterance=new SpeechSynthesisUtterance(text);
    utterance.lang=document.documentElement.lang==='en'?'en-GB':'tr-TR';
    utterance.onend=function(){update(false);};
    utterance.onerror=function(){update(false);};
    update(true);
    window.speechSynthesis.speak(utterance);
  });
})();
`;

export function renderPublishedNewsletter(
  record:PublishedNewsletter, url:string,
):{html:string,csp:string}{
  const nonce=randomBytes(16).toString('base64');
  const title=escapeShareHtml(record.title);
  const description=escapeShareHtml(record.subtitle||'Project Factory bülteni');
  const canonical=normalisePublicNewsletterUrl(url);
  const safeUrl=escapeShareHtml(canonical);
  const image=normalisePublicNewsletterUrl(record.headerImgUrl||'');
  const metaImage=image?`<meta property="og:image" content="${escapeShareHtml(image)}">`:'';
  const shareBar=readerShareBar(record.title,canonical);
  const shareSlug=canonical.match(/\/b\/([A-Za-z0-9_-]{16})(?:[?#]|$)/)?.[1]||'';
  const editHref=shareSlug?`/?edit=${encodeURIComponent(shareSlug)}`:'/';
  const html=`<!doctype html><html lang="tr"><head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="index,follow">
<title>${title} | BÜLTEN READ</title>
<meta name="description" content="${description}">
<meta property="og:type" content="article"><meta property="og:site_name" content="BÜLTEN READ">
<meta property="og:title" content="${title}"><meta property="og:description" content="${description}">
<meta property="og:url" content="${safeUrl}"><link rel="canonical" href="${safeUrl}">${metaImage}
<style>*,*::before,*::after{box-sizing:border-box}
body{margin:0;background:#e5e7eb;color:#172033;font-family:Inter,Arial,system-ui,sans-serif}
img,iframe{max-width:100%}button,a{touch-action:manipulation}
a:focus-visible,button:focus-visible{outline:3px solid #0d9488;outline-offset:3px}
.published-share{max-width:640px;margin:0 auto 24px;background:white;border-radius:12px;overflow:hidden}
.published-label{font:700 11px/1.4 system-ui;letter-spacing:.7px;color:#475569;text-align:center;margin:20px 0 0}
.published-owner{max-width:640px;margin:10px auto;text-align:right;padding:0 12px;font:700 13px system-ui}
.published-owner a{display:inline-flex;gap:5px;background:#e5f7f4;color:#115e59;text-decoration:none;padding:10px 14px;border-radius:8px}
@media(max-width:680px){body>main>div{max-width:100%!important;margin:0!important;border-radius:0!important}#bulten-reading-content{padding:18px!important}}
@media print{body{background:white}#bulten-reader-share,#speakBtn,.published-label,.published-owner,.bulten-video-player{display:none!important}}
</style></head>
<body><main><p class="published-label">BÜLTEN READ · YAYIMLANMIŞ BÜLTEN</p>
<nav class="published-owner" aria-label="Yayın düzenleme"><a href="${editHref}" target="_blank" rel="noopener noreferrer" title="Sadece bu tarayıcıda düzenleme izni bulunan yayıncılar güncelleyebilir">✎ Düzenle / Edit</a></nav>
${record.bodyHtml}
<div class="published-share">${shareBar}</div>
</main>
<script nonce="${nonce}">${READER_SPEECH_SCRIPT}</script>
<script nonce="${nonce}">${READER_SHARE_RUNTIME}</script>
</body></html>`;
  // Opaque-origin sandbox prevents published user content from accessing the
  // editor's cookies or localStorage, while allowing social links to open.
  const csp=[
    "default-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    "object-src 'none'",
    "frame-ancestors 'none'",
    "img-src https: http: data:",
    "font-src https: data:",
    "style-src 'unsafe-inline'",
    `script-src 'nonce-${nonce}'`,
    "connect-src 'none'",
    "frame-src https://www.youtube.com https://www.youtube-nocookie.com",
    "sandbox allow-scripts allow-popups allow-popups-to-escape-sandbox",
  ].join('; ');
  return {html,csp};
}
